package com.matrix.app.models;

public class ApiUser {
    private String id;
    private String name;
    private String email;
    private String role;
    private String status;

    public String getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getEmail() {
        return email;
    }

    public String getRole() {
        return role;
    }

    public String getStatus() {
        return status;
    }
}
